#!/usr/bin/env python3
"""
check_solo.py -- acceptance gate for the solo-works library (violin
Sonatas & Partitas BWV 1001-1006, cello Suites BWV 1007-1012).

DO NOT EDIT THIS FILE. It is the referee. If you believe a check is wrong,
write BLOCKED in docs/solo/STATUS.md with the evidence and stop.

Usage:
    python pipeline/check_solo.py            # full gate (Phase 1+)
    python pipeline/check_solo.py --phase 0  # inventory + untouchables only

Exit code 0 = PASS. Anything else = FAIL. Paste the full output into
docs/solo/STATUS.md for the phase you are closing.
"""
import argparse, gzip, hashlib, json, sys, warnings
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent

# BWV -> (set, work title, key, expected minimum movement-file count)
WORKS = {
    1001: ("violin", "Sonata No. 1 in G minor", "g", 4),
    1002: ("violin", "Partita No. 1 in B minor", "b", 8),
    1003: ("violin", "Sonata No. 2 in A minor", "a", 4),
    1004: ("violin", "Partita No. 2 in D minor", "d", 5),
    1005: ("violin", "Sonata No. 3 in C major", "C", 4),
    1006: ("violin", "Partita No. 3 in E major", "E", 7),
    1007: ("cello", "Suite No. 1 in G major", "G", 6),
    1008: ("cello", "Suite No. 2 in D minor", "d", 6),
    1009: ("cello", "Suite No. 3 in C major", "C", 6),
    1010: ("cello", "Suite No. 4 in E-flat major", "E-", 6),
    1011: ("cello", "Suite No. 5 in C minor", "c", 6),
    1012: ("cello", "Suite No. 6 in D major", "D", 6),
}
REQ = {"id": str, "bwv": int, "set": str, "work": str, "movement": str,
       "movementNo": int, "key": str, "kind": str, "source": str,
       "musicxml": str, "parts": list, "events": list}

fails, warns = [], []
def fail(m): fails.append(m); print("FAIL", m)
def warn(m): warns.append(m); print("warn", m)
def ok(m): print("ok  ", m)


def check_untouchables():
    base = ROOT / "docs/solo/chorales.sha256"
    bad = 0
    for line in base.read_text().splitlines():
        h, name = line.split(maxsplit=1)
        p = (ROOT / "chorales" / name) if "/" not in name else (ROOT / name)
        if not p.exists() or hashlib.sha256(p.read_bytes()).hexdigest() != h:
            bad += 1
            fail(f"untouchable file changed or missing: {p.relative_to(ROOT)}")
    if not bad:
        ok("chorale bundles, chorales/index.json, build_chorale.py, build_corpus.py unchanged")


def check_inventory():
    inv = ROOT / "data/solo/kern"
    if not inv.is_dir():
        fail("data/solo/kern/ missing"); return
    files = sorted(inv.rglob("*.krn"))
    ok(f"{len(files)} kern files under data/solo/kern/")
    for f in files:
        head = f.read_text(errors="replace")[:4000]
        if "**kern" not in head:
            fail(f"{f.name}: not a kern file (no **kern spine) -- HTML error page?")
    if not (ROOT / "docs/solo/INVENTORY.md").exists():
        fail("docs/solo/INVENTORY.md missing")


def tmap(tk):
    r = tk.renderToTimemap()
    return json.loads(r) if isinstance(r, str) else r


def check_bundles():
    import verovio
    from music21 import converter, bar
    v = verovio.toolkit().getVersion()
    if not v.startswith("6.2"):
        fail(f"pip verovio is {v}; pin verovio==6.2.1 (lockstep with vendor JS 6.2.0)")
    sdir = ROOT / "solo"
    idx_p = sdir / "index.json"
    if not idx_p.exists():
        fail("solo/index.json missing"); return
    idx = json.loads(idx_p.read_text())
    seen = {}
    for m in idx:
        for k in ("id", "bwv", "movementNo", "movement", "work", "set"):
            if k not in m:
                fail(f"index entry missing {k}: {m}")
        bid = m.get("id", "?")
        p = sdir / f"{bid}.json.gz"
        if not p.exists():
            fail(f"{bid}: bundle file missing"); continue
        try:
            d = json.loads(gzip.decompress(p.read_bytes()))
        except Exception as e:
            fail(f"{bid}: cannot read bundle ({e})"); continue
        for k, t in REQ.items():
            if not isinstance(d.get(k), t):
                fail(f"{bid}: field {k} missing or not {t.__name__}")
        if d.get("kind") != "solo":
            fail(f"{bid}: kind must be 'solo'")
        if d.get("events") != []:
            fail(f"{bid}: events must be [] (no answer key exists for these works)")
        w = WORKS.get(d.get("bwv"))
        if not w:
            fail(f"{bid}: unknown bwv {d.get('bwv')}"); continue
        if d.get("set") != w[0] or d.get("work") != w[1] or d.get("key") != w[2]:
            fail(f"{bid}: set/work/key must come from the WORKS table: {w[:3]}")
        seen.setdefault(d["bwv"], set()).add(d.get("movementNo"))
        xml = d.get("musicxml", "")
        # 1. no repeat barlines survive (371 pitfall 1)
        tmp = ROOT / "build/_check.musicxml"
        tmp.parent.mkdir(exist_ok=True)
        tmp.write_text(xml)
        try:
            s = converter.parse(str(tmp))
        except Exception as e:
            fail(f"{bid}: music21 cannot parse musicxml ({e})"); continue
        if list(s.recurse().getElementsByClass(bar.Repeat)):
            fail(f"{bid}: repeat barlines present in musicxml")
        pitches = sum(len(n.pitches) for n in s.recurse().notes
                      if not n.duration.isGrace)
        graces = sum(len(n.pitches) for n in s.recurse().notes
                     if n.duration.isGrace)
        # 2. Verovio renders it and its timemap agrees with the notes
        tk = verovio.toolkit()
        if not tk.loadData(xml):
            fail(f"{bid}: verovio loadData failed"); continue
        pages = tk.getPageCount()
        if pages < 1:
            fail(f"{bid}: verovio rendered 0 pages")
        ons = sum(len(e["on"]) for e in tmap(tk) if e.get("on"))
        if not (pitches <= ons <= pitches + graces):
            fail(f"{bid}: timemap note-ons {ons} vs score pitches {pitches} "
                 f"(+{graces} grace) -- repeats or ties not handled")
        # 3. parts.notes sane
        pn = [n for part in d["parts"] for n in part.get("notes", [])]
        if not pn:
            fail(f"{bid}: parts[].notes empty")
        elif any(not {"offset", "dur", "midi"} <= set(n) for n in pn):
            fail(f"{bid}: parts[].notes entries need offset, dur, midi")
        elif any(not (20 <= n["midi"] <= 108) for n in pn):
            fail(f"{bid}: midi values out of range")
        print(f"     {bid:<14} pages={pages:<2} notes={pitches:<5} timemap={ons}")
    for bwv, w in WORKS.items():
        got = seen.get(bwv, set())
        if len(got) < w[3]:
            fail(f"BWV {bwv}: {len(got)} movements bundled, expected >= {w[3]}")
    if len(idx) and not fails:
        ok(f"{len(idx)} solo bundles valid")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", type=int, default=1)
    a = ap.parse_args()
    print(f"== check_solo.py phase>={a.phase}")
    check_untouchables()
    check_inventory()
    if a.phase >= 1:
        check_bundles()
    print(f"== {'PASS' if not fails else 'FAIL'}  ({len(fails)} failures, {len(warns)} warnings)")
    sys.exit(0 if not fails else 1)


if __name__ == "__main__":
    main()
